"""Phase 21: assemble the final tables and the figure index (with provenance).

Reads only artefacts produced by the experiment modules (``results/tables`` and
``results/figures`` with their ``.source.json`` sidecars) and writes:

* ``results/reports/final_tables.md``: Tables 1-7 + supplementary tables;
* ``results/reports/figures_index.md``: every figure with caption and source data.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from app.experiments.recorder import DEFAULT_RESULTS

TABLES: tuple[tuple[str, str], ...] = (
    ("Table 1: Authentication performance", "authentication_table1_performance"),
    ("Table 2: Communication cost", "authentication_table2_communication"),
    ("Table 3: STRIDE comparison", "stride_table"),
    ("Table 4: ML comparison", "ids_table4_models"),
    ("Table 5: Per-attack performance", "ids_table5_per_attack"),
    ("Table 6: Adaptive framework comparison", "baseline_comparison_table"),
    ("Table 7: Scalability", "scalability_table7"),
)
SUPPLEMENTARY: tuple[tuple[str, str], ...] = (
    ("Ablation study", "ablation_table"),
    ("Sensitivity to thresholds and trust weights", "sensitivity_table"),
    ("Detector-noise stress test (SYNTHETIC false alarms)", "stress_table"),
    ("Per-attack mitigation rate by system", "baseline_comparison_per_attack_mitigation_rate"),
    ("IDS robustness (dedup test, unseen intensity)", "ids_robustness"),
    ("Per-class metrics of all IDS models", "ids_per_class_all_models"),
    ("D2D-SIM class distribution", "ids_class_distribution"),
    ("Per-operation cryptographic cost", "authentication_micro_ops"),
    ("Estimated cycles vs paper (ESTIMATE)", "authentication_cycles_estimate"),
    ("Authentication success vs PUF noise", "authentication_puf_noise"),
    ("Software PUF quality", "puf_quality_table"),
    ("Benign traffic profile", "traffic_profile_summary"),
)

HEADER = """# Final Results Tables

Generated by `python scripts/run_experiments.py` (Phase 21) from experiment artefacts only.
Every table lists the raw/processed files it was computed from (provenance sidecars).

**Result types.** Unless a column says *Literature* (copied from the D2DAP paper) or
*ESTIMATED*, every number is **Our Experimental Result** from a software simulation on the
machine recorded in each experiment's `manifest.json`. No hardware, energy or physical-PUF
results are claimed. ML results are on simulated data (D2D-SIM) and do not transfer to
real drone networks without further validation.
"""


def _sidecar(path: Path) -> dict[str, Any]:
    side = path.with_suffix("").with_suffix(".source.json") if path.suffix == ".md" else (
        path.with_name(path.stem + ".source.json"))  # fmt: skip
    if side.exists():
        data: dict[str, Any] = json.loads(side.read_text(encoding="utf-8"))
        return data
    return {}


def _section(title: str, stem: str, tables_dir: Path) -> str:
    md = tables_dir / f"{stem}.md"
    if not md.exists():
        return f"## {title}\n\n*Not available: run the corresponding experiment suite.*\n"
    side = _sidecar(tables_dir / f"{stem}.md")
    sources = ", ".join(f"`results/{s}`" for s in side.get("sources", []))
    body = md.read_text(encoding="utf-8").strip()
    meta = f"\n\n*Source data:* {sources or 'n/a'}; *seed:* {side.get('seed', 'n/a')}; " \
           f"*git commit:* `{str(side.get('git_commit', 'n/a'))[:10]}`\n"  # fmt: skip
    return f"## {title}\n\n{body}{meta}"


def build(results_dir: Path = DEFAULT_RESULTS) -> tuple[Path, Path]:
    tables_dir, fig_dir = results_dir / "tables", results_dir / "figures"
    out_dir = results_dir / "reports"
    out_dir.mkdir(parents=True, exist_ok=True)
    parts = [HEADER, *(_section(t, s, tables_dir) for t, s in TABLES), "# Supplementary tables\n",
             *(_section(t, s, tables_dir) for t, s in SUPPLEMENTARY)]  # fmt: skip
    tables_path = out_dir / "final_tables.md"
    tables_path.write_text("\n".join(parts), encoding="utf-8")
    lines = ["# Figure Index\n", "| Figure | Caption | Source data |", "|---|---|---|"]
    for png in sorted(fig_dir.glob("*.png")):
        side = fig_dir / f"{png.stem}.source.json"
        meta = json.loads(side.read_text(encoding="utf-8")) if side.exists() else {}
        srcs = "<br>".join(f"`{s}`" for s in meta.get("sources", [])) or "conceptual diagram"
        lines.append(f"| `figures/{png.name}` | {meta.get('caption', '')} | {srcs} |")
    fig_path = out_dir / "figures_index.md"
    fig_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return tables_path, fig_path
